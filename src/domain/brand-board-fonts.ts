export type BrandBoardFont = (typeof BRAND_BOARD_FONTS)[number];
export type BrandBoardFontFamily = BrandBoardFont["family"];
export const BRAND_BOARD_FONT_FAMILIES = BRAND_BOARD_FONTS.map((font) => font.family);
const inspected = new Map(fontProvenance.files.map((font) => [font.id, font]));

export function brandBoardFont(family: string): BrandBoardFont | null {
  return BRAND_BOARD_FONTS.find((font) => font.family === family) ?? null;
}
export function brandBoardFontByteLength(font: BrandBoardFont): number {
  return inspected.get(font.id)?.byteLength ?? 0;
}
export function fontSupportsBrandText(font: BrandBoardFont, text: string): boolean {
  const ranges = inspected.get(font.id)?.characterRanges;
  if (!ranges) return false;
  return [...text].every((character) => {
    const code = character.codePointAt(0)!;
    // Bidi controls can override the spelling's natural direction. Joiners used
    // by Arabic and Indic scripts remain allowed when the selected font has them.
    if (
      code < 32 ||
      (code >= 127 && code <= 159) ||
      code === 0x061c ||
      code === 0x200e ||
      code === 0x200f ||
      (code >= 0x2028 && code <= 0x202e) ||
      (code >= 0x2066 && code <= 0x2069)
    )
      return false;
    let low = 0,
      high = ranges.length - 1;
    while (low <= high) {
      const middle = (low + high) >>> 1,
        [start, end] = ranges[middle]!;
      if (code < start!) high = middle - 1;
      else if (code > end!) low = middle + 1;
      else return true;
    }
    return false;
  });
}
/** Keep ordinary Latin request bodies unchanged. Other scripts receive only
 * exact font families that can render the whole name, including mixed Latin. */
export function brandBoardFontsForText(text: string): readonly BrandBoardFont[] {
  const original = BRAND_BOARD_FONTS.slice(0, 5);
  return original.every((font) => fontSupportsBrandText(font, text))
    ? original
    : BRAND_BOARD_FONTS.filter((font) => fontSupportsBrandText(font, text));
}
export function brandTextReadiness(text: string): { supported: boolean; message: string | null } {
  if (!/[\p{L}\p{N}\p{P}\p{S}]/u.test(text))
    return { supported: false, message: "Enter a brand name before generating." };
  const supported = brandBoardFontsForText(text).length > 0;
  return {
    supported,
    message: supported
      ? null
      : "Some characters in this name cannot yet be rendered in downloadable brand assets. Remove unsupported symbols or emoji, or use a supported spelling before generating.",
  };
}
/** The first strong letter determines the text run's base direction. Each run
 * remains isolated so mixed Latin and right-to-left names keep their spelling. */
export function brandTextDirection(text: string): "ltr" | "rtl" {
  for (const character of text)
    if (/\p{L}/u.test(character)) return /[\p{Script=Arabic}\p{Script=Hebrew}]/u.test(character) ? "rtl" : "ltr";
  return "ltr";
}
export function supportedBrandBoardTypography(
  style: { family: string; weight: number; style: string },
  text?: string,
): boolean {
  const font = brandBoardFont(style.family);
  return (
    !!font &&
    style.style === "normal" &&
    Number.isInteger(style.weight) &&
    style.weight >= font.minWeight &&
    style.weight <= font.maxWeight &&
    (text === undefined || fontSupportsBrandText(font, text))
  );
}
