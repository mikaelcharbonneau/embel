// Dedicated headless fixture, independent of the shared Fluid server/browser.
// Run: node tests/features/handles-workspace/browser-check.mjs
import { build } from "esbuild";
import { chromium, expect } from "@playwright/test";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const output = resolve(".tmp/handles-browser");
await mkdir(output, { recursive: true });
await build({ entryPoints: ["tests/features/handles-workspace/preview.tsx"], bundle: true, outfile: `${output}/preview.js`, platform: "browser", jsx: "automatic", define: { "process.env.NODE_ENV": '"development"' }, tsconfig: "tsconfig.json" });
const globalCss = (await readFile("src/styles/tokens.css", "utf8")) + (await readFile("src/styles/globals.css", "utf8")).replace(/@import[^;]+;/g, "");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Handles isolated fixture</title><style>${globalCss} :root{--font-geist-sans:Arial} body{padding:24px}.page{padding:0;margin:0 auto}</style><link rel="stylesheet" href="./preview.css"></head><body><main id="root"></main><script src="./preview.js"></script></body></html>`;
await writeFile(`${output}/preview.html`, html);
const url = `file://${output}/`;
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
page.setDefaultTimeout(10000);
const errors = [], remoteRequests = [];
page.on("pageerror", error => errors.push(error.message));
await page.route("**/*", route => {
  if (!route.request().url().startsWith(url)) { remoteRequests.push(route.request().url()); return route.abort(); }
  return route.continue();
});
const checks = [];
try {
  await page.goto(`${url}preview.html`);
  await expect(page.getByRole("tab", { name: "Library" })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByText("Checks not connected")).toBeVisible();
  await expect(page.getByText("Fixture session only. No persistent storage.")).toBeVisible();
  checks.push("empty library, honest storage and unavailable checks");
  await page.getByRole("tab", { name: "Library" }).focus(); await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("tab", { name: "Search" })).toBeFocused();
  await expect(page.getByRole("tab", { name: "Search" })).toHaveAttribute("aria-selected", "true");
  checks.push("keyboard tab navigation");
  await page.getByRole("button", { name: "Build comparison" }).click();
  await expect(page.getByRole("alert")).toContainText("between 1 and 30 names");
  await page.getByRole("checkbox", { name: "Morrow Morrow · fixture" }).check();
  await page.getByRole("checkbox", { name: "Include get… and …hq variants" }).check();
  await page.getByRole("button", { name: "Build comparison" }).click();
  await expect(page.getByRole("table")).toBeVisible();
  await expect(page.getByRole("button", { name: "Check platforms", exact: true })).toBeDisabled();
  await expect(page.getByText("To check", { exact: true })).toHaveCount(9);
  await expect(page.getByText("Confirmed available", { exact: true })).toHaveCount(0);
  checks.push("imported project context and three variants × three unavailable platforms");
  await page.getByRole("checkbox", { name: "Choose @morrow on instagram for bundle", exact: true }).check();
  await page.getByRole("checkbox", { name: "Choose @getmorrow on tiktok for bundle", exact: true }).check();
  await page.getByRole("checkbox", { name: "Choose @morrowhq on youtube for bundle", exact: true }).check();
  await page.screenshot({ path: `${output}/matrix-desktop.png`, fullPage: true });
  await page.getByLabel("Bundle name", { exact: true }).fill("Morrow launch");
  await page.getByRole("button", { name: "Save bundle", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Morrow launch", exact: true })).toBeVisible();
  const entry = page.locator(".handles-saved-entry").filter({ has: page.getByText("@morrow", { exact: true }) });
  await entry.getByRole("button", { name: "Favorite", exact: true }).click();
  await entry.getByRole("button", { name: "Select", exact: true }).click();
  await entry.getByRole("button", { name: "I created this account", exact: true }).click();
  await entry.getByLabel("Account URL (optional)").fill("https://instagram.com.attacker.test/morrow");
  await entry.getByRole("button", { name: "Record my created account", exact: true }).click();
  await expect(entry.getByRole("alert")).toContainText("valid account URL on this platform");
  await entry.getByLabel("Account URL (optional)").fill("https://www.instagram.com/morrow/");
  await entry.getByRole("button", { name: "Record my created account", exact: true }).click();
  await expect(entry.getByText("Account created · user declared", { exact: true })).toBeVisible();
  await expect(entry.getByText("To check", { exact: true })).toBeVisible();
  const snapshot = JSON.parse(await page.locator("#fixture-state").textContent());
  expect(snapshot.bundles[0].entries.map(entry => entry.handle)).toEqual(["morrow", "getmorrow", "morrowhq"]);
  expect(snapshot.bundles[0].source.projectId).toBe("fixture-brand");
  expect(snapshot.bundles[0].entries[0]).toMatchObject({ favorite: true, selected: true, accountCreated: { url: "https://www.instagram.com/morrow/" }, evidence: [] });
  expect(snapshot.bundles[0].entries[1]).toMatchObject({ favorite: false, selected: false, accountCreated: null });
  checks.push("mixed bundle save, independent states, validated account declaration and preserved context");
  await entry.getByRole("button", { name: "Remove declaration", exact: true }).click();
  await expect(entry.getByRole("button", { name: "Selected", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(entry.getByRole("button", { name: "Favorited", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByLabel(/^State/).selectOption("account_created");
  await expect(page.getByRole("heading", { name: "No matching bundles" })).toBeVisible();
  await page.getByLabel(/^State/).selectOption("all");
  await page.getByLabel("Search library").fill("getmorrow");
  await expect(page.getByRole("heading", { name: "Morrow launch", exact: true })).toBeVisible();
  checks.push("remove declaration preserves favorite/selection; state and handle library filters");
  await page.screenshot({ path: `${output}/library-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/library-mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("tab", { name: "Search" }).click();
  await expect(page.getByRole("table")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: `${output}/matrix-mobile.png`, fullPage: true });
  checks.push("390px mobile library and scrollable matrix without page overflow");
  expect(errors).toEqual([]); expect(remoteRequests).toEqual([]);
  checks.push("no browser runtime errors or external requests");
  await writeFile(`${output}/verification.json`, JSON.stringify({ passed: true, checks, errors, remoteRequests, syntheticFixture: true }, null, 2));
  console.log(JSON.stringify({ passed: true, checks: checks.length, output }, null, 2));
} finally { await browser.close(); }
