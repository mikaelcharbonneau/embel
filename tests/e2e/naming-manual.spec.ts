import { expect, test } from "@playwright/test";
import { base, namingFixture, openNaming, ownerId, showNamingNames } from "./naming-brain-fixture";

test("manual name is available before the first set completes with AI unavailable", async ({ page }, info) => {
  const runtimeErrors: string[] = []; page.on("pageerror", error => runtimeErrors.push(error.message));
  const fixture = await namingFixture(page, { saved: true, count: 12, terminal: "partial" });
  fixture.state.paused = true;
  fixture.state.activeRun = { ...fixture.state.activeRun!, progress: 12, fulfillment: { status: "partial", targetCount: 100, acceptedCount: 12, missingCount: 88, coverageSatisfied: false, message: "Synthetic partial result: 12 names retained." } };
  const retained = structuredClone(fixture.state.rows), request = structuredClone(fixture.state.activeRun);
  await page.route(url => url.pathname === `${base}/feed`, async route => {
    await route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ feed: { ...fixture.feed(), availability: { status: "unavailable", code: "worker_unavailable" } } }) });
  });
  await openNaming(page);
  const field = page.getByRole("textbox", { name: "Your own name", exact: true });
  await expect(field).toBeVisible();
  await expect(page.locator("[data-naming-results-scroll]")).toHaveAttribute("hidden", "");
  await page.screenshot({ path: info.outputPath("manual-name-before-initial-set.png") });
  await field.fill("My first manual name"); await page.getByRole("button", { name: "Add name", exact: true }).click();
  await expect(page.getByRole("button", { name: "Inspect name My first manual name", exact: true })).toBeVisible();
  await page.reload(); await showNamingNames(page);
  await page.getByRole("button", { name: "Inspect name My first manual name", exact: true }).click();
  await page.getByRole("button", { name: "Use this name", exact: true }).click();
  await expect(page.getByRole("region", { name: "Name screening", exact: true })).toContainText("My first manual name");
  await page.reload(); await showNamingNames(page);
  await expect(page.getByRole("heading", { name: "My first manual name", exact: true })).toBeVisible();
  expect(fixture.state.currentSelection?.candidate.value).toBe("My first manual name");
  expect(fixture.state.manual).toHaveLength(1);
  expect(fixture.state.rows).toEqual(retained); expect(fixture.state.activeRun).toEqual(request);
  expect(fixture.mutations()).toHaveLength(0);
  expect(runtimeErrors).toEqual([]);
  await page.screenshot({ path: info.outputPath("first-manual-name-selected-after-reload.png") });
});

test("manual name after 130 generated names stays saved and selected across reload with AI unavailable", async ({ page }, info) => {
  const runtimeErrors: string[] = []; page.on("pageerror", error => runtimeErrors.push(error.message));
  const fixture = await namingFixture(page, { saved: true, count: 130, terminal: "partial" });
  const retained = structuredClone(fixture.state.rows), preferences = structuredClone(fixture.state.preferences), request = structuredClone(fixture.state.activeRun);
  await page.route(url => url.pathname === `${base}/feed`, async route => {
    await route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ feed: { ...fixture.feed(Number(new URL(route.request().url()).searchParams.get("cursorPosition") ?? 0)), availability: { status: "unavailable", code: "worker_unavailable" } } }) });
  });
  await openNaming(page); await showNamingNames(page);
  const field = page.getByRole("textbox", { name: "Your own name", exact: true });
  await field.fill("A name from me"); await page.getByRole("button", { name: "Add name", exact: true }).click();
  await expect(page.getByRole("button", { name: "Inspect name A name from me", exact: true })).toBeVisible();
  await expect(field).toHaveValue("");
  expect(fixture.state.manual).toHaveLength(1);
  await page.reload(); await showNamingNames(page);
  await page.getByRole("button", { name: "Inspect name A name from me", exact: true }).click();
  await page.getByRole("dialog", { name: "A name from me", exact: true }).getByText("More actions", { exact: true }).click();
  await page.getByRole("button", { name: "Save A name from me", exact: true }).click();
  await expect(page.getByRole("button", { name: "Unsave A name from me", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Use this name", exact: true }).click();
  await expect(page.getByRole("region", { name: "Name screening", exact: true })).toContainText("A name from me");
  await page.reload(); await showNamingNames(page);
  await expect(page.getByRole("heading", { name: "A name from me", exact: true })).toBeVisible();
  const screening = page.getByRole("region", { name: "Name screening", exact: true });
  if (!await screening.isVisible()) await page.getByRole("button", { name: "View selected name", exact: true }).click();
  await expect(screening).toContainText("A name from me");
  expect(fixture.state.currentSelection?.candidate.value).toBe("A name from me");
  expect(fixture.state.manual[0]!.retention.saved).toBe(true);
  expect(fixture.state.rows).toEqual(retained); expect(fixture.state.preferences).toEqual(preferences); expect(fixture.state.activeRun).toEqual(request);
  expect(fixture.mutations()).toHaveLength(0);
  for (const suffix of ["/imports", "/selection", "/retention"]) expect(fixture.mutations(suffix).every(row => row.account === ownerId)).toBe(true);
  expect(runtimeErrors).toEqual([]);
  await page.screenshot({ path: info.outputPath("custom-name-selected-after-reload.png") });
});

test("manual names open in the keyboard-accessible preview without selecting a name", async ({ page }, info) => {
  const fixture = await namingFixture(page, { saved: true, count: 100 });
  await openNaming(page); await showNamingNames(page);
  const input = page.getByRole("textbox", { name: "Your own name", exact: true });
  expect((await input.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  expect((await page.getByRole("button", { name: "Add name", exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await input.fill("Keyboard brand");
  await page.getByRole("button", { name: "Add name", exact: true }).click();
  const inspect = page.getByRole("button", { name: "Inspect name Keyboard brand", exact: true });
  await expect(inspect).toBeVisible(); await inspect.focus(); await page.keyboard.press("Enter");
  const preview = page.getByRole("dialog", { name: "Keyboard brand", exact: true });
  await expect(preview).toBeVisible();
  await expect(preview.getByRole("button", { name: "Use this name", exact: true })).toBeEnabled();
  await expect(preview.getByRole("button", { name: "Origin and history" })).toHaveCount(0);
  const back = page.getByRole("button", { name: "Close name preview", exact: true });
  await back.focus(); await page.keyboard.press("Enter"); await expect(inspect).toBeFocused();
  const custom = page.getByRole("region", { name: "Your custom names", exact: true });
  const card = custom.locator("article"), cardBox = (await card.boundingBox())!;
  const feedHeading = (await page.getByRole("heading", { name: "All names · 100", exact: true }).boundingBox())!;
  expect(feedHeading.y - cardBox.y - cardBox.height).toBeGreaterThanOrEqual(20);
  if (page.viewportSize()!.width <= 760) expect(cardBox.width).toBeGreaterThanOrEqual((await custom.boundingBox())!.width - 1);
  expect(await inspect.evaluate(element => getComputedStyle(element).outlineStyle)).toBe("none");
  expect(await card.evaluate(element => getComputedStyle(element).outlineStyle)).toBe("solid");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(fixture.mutations()).toHaveLength(0);
  await page.screenshot({ path: info.outputPath("manual-name-keyboard-return.png") });
});
